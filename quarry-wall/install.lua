    kept = kept + 1
    print("kept   " .. path)
  else
    local f = fs.open(path, "w")
    if not f then
      printError("could not write " .. path)
      return
    end
    f.write(files[path])
    f.close()
    written = written + 1
    print("wrote  " .. path)
  end
end

